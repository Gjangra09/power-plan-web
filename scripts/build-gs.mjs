// Builds apps-script/Engine.gs from the browser engine, so the server runs the same calculator.
//   node scripts/build-gs.mjs          writes the file
//   node scripts/build-gs.mjs --check  fails if the committed file is out of date (used by the tests)
// Apps Script has no modules: each source becomes one namespace object (Billing, Quality).
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('..', import.meta.url);
const SOURCES = [['Billing', 'js/billing.js'], ['Quality', 'js/quality.js']];
const FIXTURE = 'tests/fixtures/dhbvn-bills.json';
export const OUTPUT = fileURLToPath(new URL('apps-script/Engine.gs', root));

export function buildEngine() {
  const parts = SOURCES.map(([name, file]) => {
    const src = fs.readFileSync(new URL(file, root), 'utf8').replace(/\r\n/g, '\n');
    if (/^import /m.test(src)) throw new Error(`${file}: imports are not supported in Engine.gs`);
    const names = [...src.matchAll(/^export (?:function|const) (\w+)/gm)].map(m => m[1]);
    const body = src.replace(/^export /gm, '').trim().split('\n').map(l => (l ? '  ' + l : l)).join('\n');
    return `// ---- ${file} ----\nvar ${name} = (function () {\n${body}\n\n  return { ${names.join(', ')} };\n})();\n`;
  });
  const bills = JSON.parse(fs.readFileSync(new URL(FIXTURE, root), 'utf8'));
  return [
    '// GENERATED by scripts/build-gs.mjs from js/billing.js and js/quality.js – do not edit here.',
    '// Change the js/ files and run: node scripts/build-gs.mjs',
    '',
    ...parts,
    `// ---- ${FIXTURE} (anonymised: amounts only) – used by phase0Check() ----`,
    `var ENGINE_FIXTURE = ${JSON.stringify(bills)};`,
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = buildEngine();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== text) { console.error('apps-script/Engine.gs is out of date: run node scripts/build-gs.mjs'); process.exit(1); }
    console.log('Engine.gs is up to date');
  } else {
    fs.writeFileSync(OUTPUT, text);
    console.log('Wrote apps-script/Engine.gs');
  }
}
